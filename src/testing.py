def spherical_to_cartesian(coord):
    r, theta, phi = coord[0], coord[1], coord[2]
    x = r * jnp.sin(theta) * jnp.cos(phi)
    y = r * jnp.sin(theta) * jnp.sin(phi)
    z = r * jnp.cos(theta)
    return jnp.array([x, y, z])

def get_analytical_spherical_kind1(r, theta):
    """
    Returns analytical 3x3x3 First-Kind Christoffel matrix.
    Matches the [l, i, j] output structure generated by your transposition layout.
    """
    Gamma = jnp.zeros((3, 3, 3))
    
    # l = 0 (r slot)
    Gamma = Gamma.at[0, 1, 1].set(-r)
    Gamma = Gamma.at[0, 2, 2].set(-r * (jnp.sin(theta) ** 2))
    
    # l = 1 (theta slot)
    Gamma = Gamma.at[1, 0, 1].set(r)
    Gamma = Gamma.at[1, 1, 0].set(r)
    Gamma = Gamma.at[1, 2, 2].set(-(r**2) * jnp.sin(theta) * jnp.cos(theta))
    
    # l = 2 (phi slot)
    Gamma = Gamma.at[2, 0, 2].set(r * (jnp.sin(theta) ** 2))
    Gamma = Gamma.at[2, 2, 0].set(r * (jnp.sin(theta) ** 2))
    Gamma = Gamma.at[2, 1, 2].set((r**2) * jnp.sin(theta) * jnp.cos(theta))
    Gamma = Gamma.at[2, 2, 1].set((r**2) * jnp.sin(theta) * jnp.cos(theta))
    
    return Gamma

